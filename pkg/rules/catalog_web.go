package rules

import "regexp"

func webRules() []*Rule {
	return []*Rule{
		{
			ID:          "PAT-001",
			Name:        "innerHTML Usage",
			Description: "DOM manipulation via innerHTML — XSS risk",
			Severity:    SeverityCritical,
			Languages:   []Language{LanguageJS, LanguageTS},
			Pattern:     regexp.MustCompile(`\.innerHTML\s*[+=]`),
			CWE:         "CWE-79",
			Tags:        []string{"xss", "dom"},
		},
		{
			ID:          "PAT-002",
			Name:        "document.write() Usage",
			Description: "DOM manipulation via document.write() — XSS risk",
			Severity:    SeverityCritical,
			Languages:   []Language{LanguageJS, LanguageTS},
			Pattern:     regexp.MustCompile(`document\.write(?:ln)?\s*\(`),
			CWE:         "CWE-79",
			Tags:        []string{"xss", "dom"},
		},
		{
			ID:          "PAT-003",
			Name:        "Unsafe Regex (ReDoS)",
			Description: "Potentially vulnerable to Regular Expression Denial of Service",
			Severity:    SeverityWarning,
			Languages:   []Language{LanguageJS, LanguageTS},
			Pattern:     regexp.MustCompile(`new\s+RegExp\s*\([^)]*(?:\+|\.*)`),
			CWE:         "CWE-1333",
			Tags:        []string{"redos", "regex"},
		},
		{
			ID:          "PAT-004",
			Name:        "Prototype Pollution",
			Description: "Potential prototype pollution via object merge/extend",
			Severity:    SeverityCritical,
			Languages:   []Language{LanguageJS, LanguageTS},
			Pattern:     regexp.MustCompile(`(?:(?:__proto__|constructor)\s*\[|(?:Object\.assign|merge|extend|deepMerge)\s*\([^)]*(?:req\.|input|data|body|params))`),
			CWE:         "CWE-1321",
			Tags:        []string{"prototype-pollution"},
		},
		{
			ID:          "PAT-005",
			Name:        "Unsafe Deserialization (JS)",
			Description: "JSON parsing of untrusted data without validation",
			Severity:    SeverityWarning,
			Languages:   []Language{LanguageJS, LanguageTS},
			Pattern:     regexp.MustCompile(`JSON\.parse\s*\(\s*(?:req\.|request\.|params\.|query\.|body\.)`),
			CWE:         "CWE-502",
			Tags:        []string{"deserialization", "javascript"},
		},
		{
			ID:          "PAT-006",
			Name:        "Java Deserialization",
			Description: "Java object deserialization — remote code execution risk",
			Severity:    SeverityCritical,
			Languages:   []Language{LanguageJava},
			Pattern:     regexp.MustCompile(`(?:(?:ObjectInputStream|readObject\s*\(\))|(?:XMLDecoder|fromJson)\s*\()`),
			CWE:         "CWE-502",
			Tags:        []string{"deserialization", "java"},
		},
		{
			ID:          "PAT-007",
			Name:        "Java XXE Vulnerability",
			Description: "XML parser without disabling external entities — XXE risk",
			Severity:    SeverityCritical,
			Languages:   []Language{LanguageJava},
			Pattern:     regexp.MustCompile(`(?:(?:DocumentBuilderFactory|SAXParser|XMLReader|TransformerFactory)\s*\(\s*\))|(?:\.parse\s*\(\s*(?:request|input))`),
			CWE:         "CWE-611",
			Tags:        []string{"xxe", "java"},
		},
		{
			ID:          "PAT-008",
			Name:        "Path Traversal",
			Description: "Potential path traversal with unsanitized user input",
			Severity:    SeverityCritical,
			Pattern:     regexp.MustCompile(`(?:\.\.\/|\.\.\\|path\.join\s*\([^)]*(?:req\.|input|params|query))`),
			CWE:         "CWE-22",
			Tags:        []string{"path-traversal"},
		},
		{
			ID:          "PAT-009",
			Name:        "Open Redirect",
			Description: "Potential open redirect with user-controlled URL",
			Severity:    SeverityWarning,
			Pattern:     regexp.MustCompile(`(?:(?:redirect|redirect_url|return_url|next)\s*[:=]\s*(?:req\.|request\.|params\.|query\.)|\.redirect\s*\(\s*(?:req\.|request\.))`),
			CWE:         "CWE-601",
			Tags:        []string{"redirect"},
		},
		{
			ID:          "PAT-010",
			Name:        "Server-Side Request Forgery",
			Description: "Potential SSRF with user-controlled URL in HTTP request",
			Severity:    SeverityCritical,
			Pattern:     regexp.MustCompile(`(?:(?:fetch|axios|http\.get|https\.get|request|urllib|requests\.get|HttpClient)\s*\(\s*(?:req\.|request\.|params\.|query\.|input))`),
			CWE:         "CWE-918",
			Tags:        []string{"ssrf"},
		},
	}
}
